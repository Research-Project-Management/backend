export const REVERSE_BASE_FIELD_MAPPINGS: Record<
  string,
  Record<string, string>
> = {};
for (const [itemType, mappings] of Object.entries(BASE_FIELD_MAPPINGS)) {
  REVERSE_BASE_FIELD_MAPPINGS[itemType] = {};
  for (const [baseField, typeSpecificField] of Object.entries(mappings)) {
    REVERSE_BASE_FIELD_MAPPINGS[itemType][typeSpecificField] = baseField;
  }
}

// Helper to create field definition with order
function f(
  key: string,
  label: string,
  order: number,
  category:
    | 'core'
    | 'venue'
    | 'publication'
    | 'identifiers'
    | 'archive'
    | 'extra' = 'publication',
  type: 'text' | 'textarea' | 'date' | 'number' | 'url' = 'text',
  placeholder?: string,
  baseField?: string,
  mono?: boolean,
) {
  return { key, label, order, category, type, placeholder, baseField, mono };
}

